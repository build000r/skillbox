"""Canonical Skillbox DCG policy: fail-closed defaults + bounded overlays.

This module is the SINGLE SOURCE OF TRUTH for the contents of ``.dcg.toml``.
It replaces ad-hoc string building with a versioned policy that is:

* **fail-closed by default** -- ``[general] fail_closed = true`` so unparseable
  hook input is DENIED rather than upstream's fail-open default. Turning it off
  requires an *audited exception* (ticket + approver + expiry + reason); an
  unaudited ``fail_closed = false`` is a hard validation error.
* **closed over an approved pack set** -- overlays may only ADD packs that
  appear in :data:`APPROVED_PACKS`. An unknown or typo'd pack id is rejected
  instead of being silently written into a config dcg happily ignores.
* **narrow on allowlists** -- there is NO permissive default allowlist, and a
  rule that is effectively a wildcard (or a rule list past
  :data:`MAX_ALLOWLIST_RULES`) is rejected rather than shipped.
* **deterministic** -- rendering the same policy twice is byte-identical. Pack
  order is defaults-first then overlay order, deduped first-wins; no
  timestamps, hostnames, or absolute paths ever enter the output.

The rendered document deliberately uses only the upstream keys pinned in
:data:`UPSTREAM_KEY_PATHS`. ``dcg`` is lenient -- it silently ignores unknown
tables (the legacy ``[allowlist] rules = [...]`` block this module replaces was
never read by dcg at all) -- so drift is caught here, by validation, not by
hoping the binary complains.

CLI::

    python3 -m runtime_manager.dcg_policy render --output .dcg.toml --format json
    python3 -m runtime_manager.dcg_policy render --overlay client.json
    python3 -m runtime_manager.dcg_policy render --site-policy private-site.json
    python3 -m runtime_manager.dcg_policy validate --config .dcg.toml
"""

# CLI
# ---------------------------------------------------------------------------


def _load_overlay_file(path: str) -> list[Mapping[str, Any]]:
    try:
        raw = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise _reject(
            DCG_POLICY_MALFORMED_OVERLAY,
            f"Cannot read DCG overlay {path}: {exc}",
            path=path,
        ) from exc
    if isinstance(raw, Mapping):
        return [raw]
    if isinstance(raw, list):
        return list(raw)
    raise _reject(
        DCG_POLICY_MALFORMED_OVERLAY,
        f"DCG overlay {path} must be an object or a list of objects.",
        path=path,
    )


def _add_format(parser: argparse.ArgumentParser, *, default: Any) -> None:
    """``--format`` is accepted before OR after the subcommand.

    Subparsers use ``SUPPRESS`` as the default so an unspecified sub-level flag
    never clobbers a value already parsed at the top level.
    """
    parser.add_argument(
        "--format",
        choices=("text", "json"),
        default=default,
        help="Output format (json for agents/scripts).",
    )


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="python3 -m runtime_manager.dcg_policy",
        description="Render and validate the canonical Skillbox DCG policy.",
    )
    _add_format(parser, default="text")
    sub = parser.add_subparsers(dest="command", required=True)

    render_cmd = sub.add_parser("render", help="Render .dcg.toml from the policy.")
    render_cmd.add_argument("--output", help="Write the rendered policy to this path.")
    render_cmd.add_argument(
        "--overlay",
        action="append",
        default=[],
        metavar="PATH",
        help="JSON overlay file (object or list of objects). Repeatable, order-significant.",
    )
    _add_format(render_cmd, default=argparse.SUPPRESS)

    validate_cmd = sub.add_parser("validate", help="Validate a rendered .dcg.toml.")
    validate_cmd.add_argument(
        "--config",
        default=".dcg.toml",
        help="Path to the rendered policy (default: .dcg.toml).",
    )
    _add_format(validate_cmd, default=argparse.SUPPRESS)
    return parser


def _emit(payload: Mapping[str, Any], text_lines: Sequence[str], fmt: str) -> None:
    if fmt == "json":
        print(json.dumps(payload, indent=2, sort_keys=True))
        return
    for line in text_lines:
        print(line)


def main(argv: Sequence[str] | None = None) -> int:
    parser = _build_parser()
    args = parser.parse_args(list(argv) if argv is not None else None)
    try:
        if args.command == "render":
            overlays: list[Mapping[str, Any]] = []
            for path in args.overlay:
                overlays.extend(_load_overlay_file(path))
            policy = build_policy(overlays)
            content = render_policy(policy)
            validate_rendered(content)
            payload = policy.to_payload()
            if args.output:
                out = Path(args.output)
                if out.parent != Path(""):
                    out.parent.mkdir(parents=True, exist_ok=True)
                out.write_text(content, encoding="utf-8")
                payload["output"] = str(out)
                _emit(payload, [f"render-dcg-policy: {out}"], args.format)
            else:
                payload["content"] = content
                _emit(payload, [content.rstrip("\n")], args.format)
            return 0

        policy = load_policy_file(Path(args.config))
        payload = policy.to_payload()
        payload["config"] = args.config
        _emit(payload, [f"ok: {args.config}"], args.format)
        return 0
    except SkillboxError as exc:
        if args.format == "json":
            print(json.dumps(exc.to_payload(), indent=2, sort_keys=True))
        else:
            print(f"{exc.code}: {exc.message}", file=sys.stderr)
        return 1



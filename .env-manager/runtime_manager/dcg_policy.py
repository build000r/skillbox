def build_policy(
    overlays: Iterable[Mapping[str, Any]] = (),
    *,
    base_packs: Sequence[str] = DEFAULT_PACKS,
    site_policies: Iterable[DcgSitePolicy] = (),
    now: date | None = None,
) -> DcgPolicy:
    """Merge ``overlays`` onto the fail-closed defaults and validate the result.

    Precedence is deterministic and additive: the base packs come first in
    declared order, then each overlay's packs in overlay order, deduped
    first-wins. Overlays can only ADD -- there is no removal verb, so no client
    overlay can quietly shrink the guard. ``fail_closed`` is the one scalar an
    overlay may overwrite, and only downward with an audited exception attached.
    """
    packs: list[str] = []
    for pack in base_packs:
        normalized = _normalize_pack(pack, source="defaults")
        if normalized not in packs:
            packs.append(normalized)

    allowlist: list[str] = []
    blocklist: list[DcgBlockRule] = list(DEFAULT_BLOCK_RULES)
    default_agent: DcgAgentProfile | None = None
    unknown_agent: DcgAgentProfile | None = None
    fail_closed = True
    exception: FailOpenException | None = None

    sites = list(site_policies)
    if len(sites) > MAX_SITE_POLICIES:
        raise _site_reject(
            f"At most {MAX_SITE_POLICIES} site policies may be composed.", field="sites"
        )
    site_ids: set[str] = set()
    block_patterns = {rule.pattern for rule in blocklist}
    for index, site in enumerate(sites):
        if not isinstance(site, DcgSitePolicy):
            raise _site_reject(
                f"Site policy #{index} must be a validated DcgSitePolicy.", field="sites"
            )
        if site.site_id in site_ids:
            raise _site_reject("Site policy ids must be unique.", field="site_id")
        site_ids.add(site.site_id)
        for pack in site.packs:
            normalized = _normalize_pack(pack, source=f"site:{site.site_id}")
            if normalized not in packs:
                packs.append(normalized)
        for rule in site.allowlist:
            normalized = _normalize_allowlist_rule(rule, source=f"site:{site.site_id}")
            if normalized not in allowlist:
                allowlist.append(normalized)
        for rule in site.blocklist:
            normalized = _normalize_block_rule(
                rule.to_payload(), source=f"site:{site.site_id}"
            )
            if normalized.pattern in block_patterns:
                raise _reject(
                    DCG_POLICY_DUPLICATE_BLOCK_PATTERN,
                    "Site block pattern duplicates a default or earlier site pattern.",
                    site_id=site.site_id,
                )
            block_patterns.add(normalized.pattern)
            blocklist.append(normalized)
        if site.default_agent is not None:
            default_agent = site.default_agent
        if site.unknown_agent is not None:
            unknown_agent = site.unknown_agent

    for index, overlay in enumerate(overlays):
        if not isinstance(overlay, Mapping):
            raise _reject(
                DCG_POLICY_MALFORMED_OVERLAY,
                f"DCG overlay #{index} must be a mapping; got {type(overlay).__name__}.",
                overlay_index=index,
            )
        source = str(overlay.get("id") or f"overlay#{index}")
        unknown = sorted(set(overlay) - OVERLAY_KEYS)
        if unknown:
            raise _reject(
                DCG_POLICY_MALFORMED_OVERLAY,
                f"DCG overlay {source} carries unknown keys: {', '.join(unknown)}.",
                source=source,
                unknown=unknown,
                allowed=sorted(OVERLAY_KEYS),
            )

        raw_packs = overlay.get("packs") or []
        if isinstance(raw_packs, (str, bytes)) or not isinstance(raw_packs, Sequence):
            raise _reject(
                DCG_POLICY_MALFORMED_OVERLAY,
                f"DCG overlay {source} 'packs' must be a list of pack ids.",
                source=source,
            )
        for raw_pack in raw_packs:
            pack = _normalize_pack(raw_pack, source=source)
            if pack not in packs:
                packs.append(pack)

        raw_rules = overlay.get("allowlist") or []
        if isinstance(raw_rules, (str, bytes)) or not isinstance(raw_rules, Sequence):
            raise _reject(
                DCG_POLICY_MALFORMED_ALLOWLIST,
                f"DCG overlay {source} 'allowlist' must be a list of command rules.",
                source=source,
            )
        for raw_rule in raw_rules:
            rule = _normalize_allowlist_rule(raw_rule, source=source)
            if rule not in allowlist:
                allowlist.append(rule)

        if "fail_closed" in overlay:
            requested = overlay["fail_closed"]
            if not isinstance(requested, bool):
                raise _reject(
                    DCG_POLICY_MALFORMED_OVERLAY,
                    f"DCG overlay {source} 'fail_closed' must be a boolean.",
                    source=source,
                    fail_closed=repr(requested),
                )
            if requested:
                fail_closed = True
                exception = None
            else:
                exception = _normalize_exception(
                    overlay.get("fail_closed_exception"), source=source
                )
                fail_closed = False
        elif "fail_closed_exception" in overlay:
            raise _reject(
                DCG_POLICY_MALFORMED_OVERLAY,
                f"DCG overlay {source} declares a fail_closed exception without "
                "setting fail_closed = false.",
                source=source,
            )

    if len(allowlist) > MAX_ALLOWLIST_RULES:
        raise _reject(
            DCG_POLICY_BROAD_ALLOWLIST,
            f"DCG allowlist has {len(allowlist)} rules; the policy ceiling is "
            f"{MAX_ALLOWLIST_RULES}.",
            rule_count=len(allowlist),
            max_rules=MAX_ALLOWLIST_RULES,
        )
    if len(blocklist) > MAX_BLOCKLIST_RULES:
        raise _reject(
            DCG_POLICY_MALFORMED_BLOCKLIST,
            f"DCG blocklist has {len(blocklist)} rules; the policy ceiling is "
            f"{MAX_BLOCKLIST_RULES}.",
            rule_count=len(blocklist),
            max_rules=MAX_BLOCKLIST_RULES,
        )

    if not fail_closed and exception is not None:
        today = now or date.today()
        if date.fromisoformat(exception.expires) < today:
            raise _reject(
                DCG_POLICY_EXPIRED_EXCEPTION,
                f"DCG fail_closed exception {exception.ticket} expired on "
                f"{exception.expires}; fail-closed is restored.",
                ticket=exception.ticket,
                expires=exception.expires,
                today=today.isoformat(),
            )

    return DcgPolicy(
        packs=tuple(packs),
        allowlist=tuple(allowlist),
        blocklist=tuple(blocklist),
        fail_closed=fail_closed,
        exception=exception,
        default_agent=default_agent,
        unknown_agent=unknown_agent,
    )


# ---------------------------------------------------------------------------
# Rendering
# ---------------------------------------------------------------------------


def _toml_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _toml_array(values: Sequence[str]) -> str:
    return "[" + ", ".join(_toml_string(value) for value in values) + "]"


def _toml_block_array(values: Sequence[DcgBlockRule]) -> str:
    entries = (
        f"{{ pattern = {_toml_string(rule.pattern)}, reason = {_toml_string(rule.reason)} }}"
        for rule in values
    )
    return "[" + ", ".join(entries) + "]"


def _render_agent_profile(
    lines: list[str], name: str, profile: DcgAgentProfile | None
) -> None:
    if profile is None:
        return
    lines.extend(["", f"[agents.{name}]"])
    if profile.trust_level is not None:
        lines.append(f"trust_level = {_toml_string(profile.trust_level)}")
    if profile.extra_packs:
        lines.append(f"extra_packs = {_toml_array(profile.extra_packs)}")
    if profile.disabled_allowlist is not None:
        value = "true" if profile.disabled_allowlist else "false"
        lines.append(f"disabled_allowlist = {value}")


def render_policy(policy: DcgPolicy) -> str:
    """Render ``policy`` as ``.dcg.toml`` text. Deterministic, byte-for-byte."""
    lines: list[str] = [GENERATED_MARKER, POLICY_MARKER]
    if policy.fail_closed:
        lines.append("# fail_closed: unparseable hook input is DENIED, never allowed.")
    else:
        lines.append("# fail_closed: DISABLED under an audited exception.")
        for field in EXCEPTION_FIELDS:
            assert policy.exception is not None  # guaranteed by build_policy
            lines.append(f"#   {field}: {getattr(policy.exception, field)}")
    lines.extend(
        [
            "",
            "[general]",
            f"fail_closed = {'true' if policy.fail_closed else 'false'}",
            "",
            "[packs]",
            f"enabled = {_toml_array(policy.packs)}",
        ]
    )
    if policy.allowlist or policy.blocklist:
        lines.extend(["", "[overrides]"])
        if policy.allowlist:
            lines.append(f"allow = {_toml_array(policy.allowlist)}")
        if policy.blocklist:
            lines.append(f"block = {_toml_block_array(policy.blocklist)}")
    _render_agent_profile(lines, "default", policy.default_agent)
    _render_agent_profile(lines, "unknown", policy.unknown_agent)
    return "\n".join(lines) + "\n"


def render(
    overlays: Iterable[Mapping[str, Any]] = (),
    *,
    base_packs: Sequence[str] = DEFAULT_PACKS,
    site_policies: Iterable[DcgSitePolicy] = (),
    now: date | None = None,
) -> str:
    """Build + render in one step (the common caller path)."""
    return render_policy(
        build_policy(
            overlays,
            base_packs=base_packs,
            site_policies=site_policies,
            now=now,
        )
    )


# ---------------------------------------------------------------------------
# Parse-back / upstream validation
# ---------------------------------------------------------------------------


def key_paths(document: Mapping[str, Any]) -> set[tuple[str, ...]]:
    """Flatten a parsed TOML document into ``(table, key)`` paths."""
    paths: set[tuple[str, ...]] = set()

    def walk(node: Mapping[str, Any], prefix: tuple[str, ...]) -> None:
        for key, value in node.items():
            path = prefix + (str(key),)
            if isinstance(value, Mapping):
                walk(value, path)
            else:
                paths.add(path)

    walk(document, ())
    return paths


def validate_rendered(
    text: str, *, expected_policy: DcgPolicy | None = None
) -> DcgPolicy:
    """Parse rendered policy text back and re-assert every policy invariant.

    This is the upstream-syntax gate: the document must parse as TOML, must use
    ONLY the keys pinned in :data:`UPSTREAM_KEY_PATHS`, and must round-trip to a
    policy that ``build_policy`` would also accept.
    """
    if not text.startswith(GENERATED_MARKER):
        raise _reject(
            DCG_POLICY_UPSTREAM_MISMATCH,
            "Rendered DCG policy is missing the generated-ownership marker.",
        )
    try:
        document = tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        raise _reject(
            DCG_POLICY_UPSTREAM_MISMATCH,
            f"Rendered DCG policy is not valid TOML: {exc}",
        ) from exc

    unexpected = sorted(key_paths(document) - UPSTREAM_KEY_PATHS)
    if unexpected:
        raise _reject(
            DCG_POLICY_UPSTREAM_MISMATCH,
            "Rendered DCG policy uses keys outside the pinned upstream set: "
            + ", ".join(".".join(path) for path in unexpected),
            unexpected=[".".join(path) for path in unexpected],
            allowed=sorted(".".join(path) for path in UPSTREAM_KEY_PATHS),
        )

    general = document.get("general") or {}
    fail_closed = general.get("fail_closed")
    if not isinstance(fail_closed, bool):
        raise _reject(
            DCG_POLICY_UPSTREAM_MISMATCH,
            "Rendered DCG policy must declare a boolean [general] fail_closed.",
        )

    packs = (document.get("packs") or {}).get("enabled") or []
    overrides = document.get("overrides") or {}
    allowlist = overrides.get("allow") or []
    raw_blocklist = overrides.get("block") or []
    if isinstance(raw_blocklist, (str, bytes)) or not isinstance(raw_blocklist, Sequence):
        raise _reject(
            DCG_POLICY_MALFORMED_BLOCKLIST,
            "Rendered DCG block override must be a list.",
        )
    blocklist = tuple(
        _normalize_block_rule(rule, source="rendered") for rule in raw_blocklist
    )
    if len(blocklist) > MAX_BLOCKLIST_RULES:
        raise _reject(
            DCG_POLICY_MALFORMED_BLOCKLIST,
            "Rendered DCG block override exceeds the policy ceiling.",
            rule_count=len(blocklist),
            max_rules=MAX_BLOCKLIST_RULES,
        )
    patterns = [rule.pattern for rule in blocklist]
    if len(patterns) != len(set(patterns)):
        raise _reject(
            DCG_POLICY_DUPLICATE_BLOCK_PATTERN,
            "Rendered DCG policy contains duplicate block patterns.",
        )
    overlay: dict[str, Any] = {"id": "rendered", "packs": packs, "allowlist": allowlist}
    if not fail_closed:
        overlay["fail_closed"] = False
        overlay["fail_closed_exception"] = _exception_from_comments(text)
    # Re-running the builder proves packs, allowlist, and fail-closed state are
    # admissible. Expiry is intentionally not re-checked here so an already-
    # shipped config validates the same way on any day.
    base = build_policy([overlay], base_packs=(), now=date.min)

    raw_agents = document.get("agents") or {}
    if not isinstance(raw_agents, Mapping) or set(raw_agents) - SITE_AGENT_KEYS:
        raise _reject(
            DCG_POLICY_UPSTREAM_MISMATCH,
            "Rendered DCG policy uses an unpinned agent profile.",
        )
    default_agent = (
        _normalize_agent_profile(raw_agents["default"], field="agents.default")
        if "default" in raw_agents
        else None
    )
    unknown_agent = (
        _normalize_agent_profile(raw_agents["unknown"], field="agents.unknown")
        if "unknown" in raw_agents
        else None
    )
    candidate = DcgPolicy(
        packs=base.packs,
        allowlist=base.allowlist,
        blocklist=blocklist,
        fail_closed=base.fail_closed,
        exception=base.exception,
        default_agent=default_agent,
        unknown_agent=unknown_agent,
    )
    if expected_policy is None:
        # Backward-compatible overlay validation: packs/allow/fail-closed may
        # vary, but site-only blocks and agent profiles require the caller to
        # supply the exact composition they expected.
        if blocklist != DEFAULT_BLOCK_RULES or any(
            profile is not None for profile in (default_agent, unknown_agent)
        ):
            raise _reject(
                DCG_POLICY_UPSTREAM_MISMATCH,
                "Rendered site policy requires its expected composed policy.",
            )
        expected = candidate
    else:
        expected = expected_policy
    if candidate != expected:
        raise _reject(
            DCG_POLICY_UPSTREAM_MISMATCH,
            "Rendered DCG policy does not match the expected composed policy.",
        )
    canonical = render_policy(expected)
    if text != canonical:
        raise _reject(
            DCG_POLICY_UPSTREAM_MISMATCH,
            "Rendered DCG policy is not the canonical deterministic rendering.",
        )
    return candidate


def _exception_from_comments(text: str) -> dict[str, str]:
    """Recover the audited-exception record from the rendered header comments."""
    values: dict[str, str] = {}
    for line in text.splitlines():
        if not line.startswith("#   "):
            continue
        field, _, value = line[4:].partition(": ")
        if field in EXCEPTION_FIELDS and value:
            values[field] = value
    return values


def load_policy_file(
    path: Path, *, expected_policy: DcgPolicy | None = None
) -> DcgPolicy:
    """Validate an on-disk ``.dcg.toml`` rendered by this module."""
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise _reject(
            DCG_POLICY_UPSTREAM_MISMATCH,
            f"Cannot read DCG policy at {path}: {exc}",
            path=str(path),
        ) from exc
    return validate_rendered(text, expected_policy=expected_policy)


